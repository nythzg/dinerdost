type Language = "en" | "hi";
const LanguageContext = createContext<{
  language: Language;
  setLanguage: (value: Language) => void;
}>({ language: "en", setLanguage: () => {} });
export function translateStaff(value: string, language: Language) {
  if (language === "en") return value;
  const key = value.trim();
  return hindi[key] ? value.replace(key, hindi[key]) : value;
}
export function StaffLanguage({
  account,
  children,
}: {
  account: string;
  children: ReactNode;
}) {
  const [stored, setStored] = useState<{ key: string; value: Language }>({
    key: "",
    value: "en",
  });
  const key = "dd-staff-language-" + account,
    language = stored.key === key ? stored.value : "en";
  useEffect(() => {
    setStored({ key, value: localStorage.getItem(key) === "hi" ? "hi" : "en" });
  }, [key]);
  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage: (value) => {
          localStorage.setItem(key, value);
          setStored({ key, value });
        },
      }}
    >
      <div lang={language} style={{ display: "contents" }}>
        {children}
      </div>
    </LanguageContext.Provider>
  );
}
export function T({ children }: { children: ReactNode }) {
  const { language } = useContext(LanguageContext);
  return typeof children === "string"
    ? translateStaff(children, language)
    : children;
}
export function useStaffTranslation() {
  const { language } = useContext(LanguageContext);
  return (value: string) => translateStaff(value, language);
}
export function LanguageSelect() {
  const { language, setLanguage } = useContext(LanguageContext);
  return (
    <select
      className="staff-language"
      aria-label="Interface language"
      value={language}
      onChange={(e) => setLanguage(e.target.value as Language)}
    >
      <option value="en">English</option>
      <option value="hi">हिन्दी</option>
    </select>
  );
}
